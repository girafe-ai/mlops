"""Cityscapes Dataset and semantic label mapping shared by both training implementations."""

import csv
from collections.abc import Callable
from pathlib import Path

import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision.transforms import functional as transforms_functional


class CityscapesSegmentationDataset(Dataset):
    """Read Cityscapes RGB images and fine label-ID masks from a CSV manifest.

    The manifest is generated by the DVC/PostgreSQL pipeline and contains image
    and annotation paths. The corresponding label-ID PNG is derived from each
    polygon annotation path.

    Args:
        manifest_path: CSV file with Cityscapes image metadata.
        split: Dataset split to select, such as ``train`` or ``val``.
        class_ids: Mapping of Cityscapes label IDs to contiguous training IDs.
        ignore_index: Configured target value for label IDs outside ``class_ids``.
        transform: Optional callable that receives a PIL image and mask and
            returns a pair of tensors.
    """

    def __init__(
        self,
        manifest_path: Path,
        split: str,
        class_ids: dict[int, int],
        ignore_index: int,
        transform: Callable[
            [Image.Image, Image.Image], tuple[torch.Tensor, torch.Tensor]
        ]
        | None = None,
    ) -> None:
        self.class_ids = class_ids
        self.transform = transform
        self.ignore_index = ignore_index
        with manifest_path.open("r", encoding="utf-8", newline="") as manifest_file:
            self.samples = [
                row for row in csv.DictReader(manifest_file) if row["split"] == split
            ]

    def __len__(self) -> int:
        """Return the number of samples in the requested split."""
        return len(self.samples)

    def __getitem__(self, index: int) -> dict[str, object]:
        """Load one RGB image and its mapped segmentation target."""
        row = self.samples[index]
        image = Image.open(row["image_path"]).convert("RGB")
        mask = Image.open(_label_path(Path(row["annotation_path"])))

        if self.transform is None:
            image_tensor = transforms_functional.pil_to_tensor(image).float() / 255
            mask_tensor = torch.as_tensor(
                transforms_functional.pil_to_tensor(mask).squeeze(0), dtype=torch.long
            )
        else:
            image_tensor, mask_tensor = self.transform(image, mask)

        return {
            "image": image_tensor,
            "mask": remap_cityscapes_mask(
                mask_tensor,
                class_ids=self.class_ids,
                ignore_index=self.ignore_index,
            ),
            "image_id": row["image_id"],
        }


def remap_cityscapes_mask(
    mask: torch.Tensor,
    class_ids: dict[int, int],
    ignore_index: int,
) -> torch.Tensor:
    """Map original Cityscapes IDs to contiguous class indices.

    Args:
        mask: Original ``labelIds`` mask with Cityscapes integer IDs.
        class_ids: Mapping from original ID to model class index.
        ignore_index: Value assigned to every unselected class.

    Returns:
        A ``torch.long`` mask suitable for ``CrossEntropyLoss``.
    """
    remapped = torch.full_like(mask, fill_value=ignore_index, dtype=torch.long)
    for cityscapes_id, training_id in class_ids.items():
        remapped[mask == cityscapes_id] = training_id
    return remapped


def _label_path(annotation_path: Path) -> Path:
    """Return the fine label-ID image corresponding to a polygon JSON path."""
    return annotation_path.with_name(
        annotation_path.name.replace("_gtFine_polygons.json", "_gtFine_labelIds.png")
    )
